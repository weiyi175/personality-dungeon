def _now_utc() -> datetime:
    return datetime.now(timezone.utc).replace(microsecond=0)


def _normalize_text(text: str) -> str:
    return text.replace("\r", " ").replace("\n", " ").replace("\t", " ").strip()


def _clamp(v: float) -> float:
    return max(-1.0, min(1.0, v))


def _build_vector(trait: str, sign: str, offset: int) -> dict[str, float]:
    base = TRAIT_VECTORS.get((trait, sign), {trait: (0.90 if sign == "pos" else -0.90)})
    jitter = [-0.04, 0.0, 0.04, 0.02, -0.02][offset % 5]
    vector: dict[str, float] = {t: 0.0 for t in PERSONALITY_BASIS}
    for t, v in base.items():
        if t in vector:
            vector[t] = _clamp(v + jitter)
    return vector


def _load_existing_texts(tsv_path: Path) -> set[str]:
    if not tsv_path.exists():
        return set()
    texts: set[str] = set()
    with tsv_path.open("r", encoding="utf-8", newline="") as f:
        reader = csv.DictReader(f, delimiter="\t")
        for row in reader:
            t = _normalize_text(row.get("text", ""))
            if t:
                texts.add(t)
    return texts


def _length_bucket(text: str) -> str:
    n = len(text)
    if 1 <= n <= 5:
        return "short"
    if 6 <= n <= 12:
        return "medium"
    if 13 <= n <= 20:
        return "long"
    return "other"


def _is_valid_length(text: str) -> bool:
    return 1 <= len(text) <= 20


def _append_tsv(tsv_path: Path, rows: list[dict[str, Any]]) -> None:
    needs_header = not tsv_path.exists() or tsv_path.stat().st_size == 0
    tsv_path.parent.mkdir(parents=True, exist_ok=True)
    fields = ["timestamp", "request_id", "text", "length", "model", "temperature",
              "source", "session_id", "user_id", *PERSONALITY_BASIS]
    with tsv_path.open("a", encoding="utf-8", newline="") as f:
        writer = csv.DictWriter(f, fieldnames=fields, delimiter="\t")
        if needs_header:
            writer.writeheader()
        for row in rows:
            writer.writerow(row)


def _append_jsonl(jsonl_path: Path, rows: list[dict[str, Any]]) -> None:
    jsonl_path.parent.mkdir(parents=True, exist_ok=True)
    with jsonl_path.open("a", encoding="utf-8") as f:
        for row in rows:
            payload = {
                "timestamp": row["timestamp"],
                "request_id": row["request_id"],
                "text": row["text"],
                "length": row["length"],
                "model": row["model"],
                "temperature": float(row["temperature"]),
                "source": row["source"],
                "session_id": row["session_id"],
                "user_id": row["user_id"],
                "vector": {t: float(row[t]) for t in PERSONALITY_BASIS},
            }
            f.write(json.dumps(payload, ensure_ascii=False) + "\n")


