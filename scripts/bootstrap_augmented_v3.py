def _generate_tier2_texts(trait: str, sign: str, bucket: str) -> list[str]:
    """使用模板組合生成候選文本（Tier-2）
    
    TEMPLATE_PARTS 的 suffixes 同時包含 medium 和 long 長度的後綴，
    此函式過濾出符合目標 bucket 的組合。
    """
    prefixes, suffixes = TEMPLATE_PARTS.get((trait, sign), ([], []))
    candidates: list[str] = []
    seen_local: set[str] = set()
    for pre in prefixes:
        for suf in suffixes:
            text = pre + suf
            text = _normalize_text(text)
            if text in seen_local:
                continue
            if not _is_valid_length(text):
                continue
            length_b = _length_bucket(text)
            if length_b == bucket:
                candidates.append(text)
                seen_local.add(text)
    return candidates


def generate(
    target: int,
    existing_texts: set[str],
    session_id: str,
    base_timestamp: datetime,
) -> tuple[list[dict[str, Any]], dict[str, Any]]:
    """
    配額生成策略（雙層）：
      - short 配額 = target * 0.23（≥22%）
      - medium 配額 = target * 0.39
      - long   配額 = 其餘

    Tier-1：逐一取出 VOCAB 中的顯式文本
    Tier-2：若配額未滿，由 TEMPLATE_PARTS 前綴×後綴全排列補充
    """
    short_quota = int(target * 0.23)
    medium_quota = int(target * 0.39)
    long_quota = target - short_quota - medium_quota

    buckets_remaining = {"short": short_quota, "medium": medium_quota, "long": long_quota}

    rows: list[dict[str, Any]] = []
    seen: set[str] = set(existing_texts)
    counter = 0

    group_stats: dict[str, dict[str, int]] = {}

    traits = ["assertiveness", "optimism", "suspicion", "endurance", "curiosity"]
    signs = ["pos", "neg"]

    # 每個 (trait, sign) group 各得到均等配額，確保 5 個弱 trait 都被覆蓋
    n_groups = len(traits) * len(signs)  # 10
    per_group_cap = max(1, target // n_groups)  # 100 per group

    def _emit(text: str, trait: str, sign: str, bucket: str, key: str) -> bool:
        nonlocal counter
        text = _normalize_text(text)
        if not _is_valid_length(text):
            return False
        if text in seen:
            return False
        if buckets_remaining[bucket] <= 0:
            return False
        seen.add(text)
        vector = _build_vector(trait, sign, offset=counter)
        ts = (base_timestamp + timedelta(seconds=counter)).strftime("%Y-%m-%dT%H:%M:%SZ")
        row: dict[str, Any] = {
            "timestamp": ts,
            "request_id": uuid4().hex,
            "text": text,
            "length": len(text),
            "model": "bootstrap-v3-weak-trait",
            "temperature": 0.35,
            "source": "augmented",
            "session_id": session_id,
            "user_id": None,
        }
        row.update(vector)
        rows.append(row)
        group_stats[key][bucket] += 1
        buckets_remaining[bucket] -= 1
        counter += 1
        return True

    for trait in traits:
        for sign in signs:
            key = f"{trait}_{sign}"
            group_stats[key] = {"short": 0, "medium": 0, "long": 0, "skipped": 0}
            group_counter = 0  # 本 group 已 emit 數量
            for bucket in ["short", "medium", "long"]:
                if group_counter >= per_group_cap:
                    break
                # Tier-1: explicit vocab
                for text in VOCAB.get((trait, sign, bucket), []):
                    if _emit(text, trait, sign, bucket, key):
                        group_counter += 1
                    else:
                        group_stats[key]["skipped"] += 1
                    if group_counter >= per_group_cap:
                        break
                    if counter >= target:
                        break
                if group_counter >= per_group_cap or counter >= target:
                    break
                # Tier-2: template combo fill
                for text in _generate_tier2_texts(trait, sign, bucket):
                    if _emit(text, trait, sign, bucket, key):
                        group_counter += 1
                    if group_counter >= per_group_cap:
                        break
                    if counter >= target:
                        break
                if group_counter >= per_group_cap or counter >= target:
                    break
            if counter >= target:
                break
        if counter >= target:
            break

    bucket_counts = Counter(_length_bucket(r["text"]) for r in rows)
    total = len(rows)
    short_pct = bucket_counts.get("short", 0) / total if total else 0.0
    stats = {
        "session_id": session_id,
        "target": target,
        "generated": total,
        "bucket_counts": dict(bucket_counts),
        "short_pct": round(short_pct, 4),
        "short_quota_met": short_pct >= 0.22,
        "group_stats": group_stats,
        "vocab_coverage": {
            f"{t}_{s}_{b}": len(VOCAB.get((t, s, b), []))
            for t in traits for s in signs
            for b in ["short", "medium", "long"]
        },
    }
    return rows, stats


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        description="v3 augmented 重生器：專攻弱 trait + 強制 1-5 字短句 ≥ 22%"
    )
    parser.add_argument("--target-additions", type=int, default=1000,
                        help="要新增的行數（預設 1000）")
    parser.add_argument("--source-tsv", type=Path, default=DEFAULT_SOURCE_TSV,
                        help="讀取現有文本以去重（預設 personality_text_pairs.tsv）")
    parser.add_argument("--tsv", type=Path, default=DEFAULT_TSV,
                        help="輸出 TSV 路徑（預設 *_regen_v3.tsv）")
    parser.add_argument("--jsonl", type=Path, default=DEFAULT_JSONL,
                        help="輸出 JSONL 路徑（預設 *_regen_v3.jsonl）")
    parser.add_argument("--manifest", type=Path, default=DEFAULT_MANIFEST,
                        help="Manifest JSON 路徑")
    parser.add_argument("--session-id", default=None, help="自訂 session_id")
    parser.add_argument("--dry-run", action="store_true",
                        help="不寫入輸出，只列印統計")
    args = parser.parse_args(argv)

    session_id = args.session_id or f"bootstrap_v3_{_now_utc().strftime('%Y%m%d_%H%M%S')}"
    base_ts = _now_utc()

    # 從 source TSV 讀現有文本去重
    existing_texts = _load_existing_texts(args.source_tsv)
    # 也從目標輸出去重（若已存在）
    if args.tsv != args.source_tsv:
        existing_texts |= _load_existing_texts(args.tsv)

    rows, stats = generate(args.target_additions, existing_texts, session_id, base_ts)

    stats["dry_run"] = args.dry_run
    stats["source_tsv"] = str(args.source_tsv)
    stats["output_tsv"] = str(args.tsv)
    stats["output_jsonl"] = str(args.jsonl)

    if not args.dry_run:
        _append_tsv(args.tsv, rows)
        _append_jsonl(args.jsonl, rows)
        args.manifest.parent.mkdir(parents=True, exist_ok=True)
        args.manifest.write_text(json.dumps(stats, ensure_ascii=False, indent=2), encoding="utf-8")
        print(f"[+] wrote {len(rows)} rows → {args.tsv}", file=sys.stderr)

    print(json.dumps(stats, ensure_ascii=False, indent=2))
    return 0 if stats["generated"] >= args.target_additions else 1


if __name__ == "__main__":
    raise SystemExit(main())
