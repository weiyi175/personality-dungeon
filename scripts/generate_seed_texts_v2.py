def generate_seed_csv(output_path: Path):
    """生成高品質種子文本 CSV"""
    rows = []
    
    for trait in TRAITS:
        endpoints = SEED_TEXTS[trait]
        for endpoint in ["high", "low", "neutral"]:
            texts = endpoints[endpoint]
            for text, length_bucket in texts:
                rows.append({
                    "text": text,
                    "length_bucket": length_bucket,
                    "trait": trait,
                    "endpoint": endpoint,
                })
    
    # 寫入 CSV
    output_path.parent.mkdir(parents=True, exist_ok=True)
    with open(output_path, "w", newline="", encoding="utf-8") as f:
        writer = csv.DictWriter(f, fieldnames=["text", "length_bucket", "trait", "endpoint"])
        writer.writeheader()
        writer.writerows(rows)
    
    # 統計
    print(f"✓ 已生成 {len(rows)} 句種子文本")
    print(f"  儲存至: {output_path}")
    
    # 分佈統計
    buckets = {}
    for row in rows:
        b = row["length_bucket"]
        buckets[b] = buckets.get(b, 0) + 1
    
    print("\n長度分佈:")
    for b in sorted(buckets.keys()):
        pct = 100 * buckets[b] / len(rows)
        print(f"  {b}: {buckets[b]} ({pct:.1f}%)")
    
    # Trait 分佈
    trait_counts = {}
    for row in rows:
        t = row["trait"]
        trait_counts[t] = trait_counts.get(t, 0) + 1
    
    print("\nTrait 分佈 (每個 trait 應有 ~50–60 筆):")
    for t in TRAITS:
        print(f"  {t}: {trait_counts[t]}")

